"""Assign every Round 2 dataset item to train, selection or blind2 and write configs/suites-r2.yaml.

The rules are in evotaste/external.py (docs/dev/ROUND2_SPEC.md, WP-D): Round 1's frozen parts, held-out halves by
text hash, a seeded draw of the unseen units, de-duplication with the vault taking precedence, and the filters. Every
reference is checked by its verifier; the verdicts of train and selection items are stored, those of the vault never.
Blind question texts are read only to hash and de-duplicate them; for the vault the file holds counts and a hash of
each source's uid list, never the items. The Round 1 procedural families are copied from configs/suites.yaml.

Usage (compute host, repository root, after `source scripts/env.sh`):
    python scripts/make_suites_r2.py --download   # once: fill the dataset cache through the mirror
    python scripts/make_suites_r2.py              # write configs/suites-r2.yaml
"""

import argparse
import collections
import os
import sys
import time
from pathlib import Path

import yaml

OUT = Path("configs/suites-r2.yaml")
ROUND1_SUITES = Path("configs/suites.yaml")
TOKENIZER = "Qwen/Qwen3-1.7B"
MATH_CATEGORIES = {"arithmetic", "algebra", "geometry"}  # Round 1 categories whose procedural families count as math


def download() -> None:
    os.environ["HF_DATASETS_OFFLINE"] = "0"
    from datasets import load_dataset

    from evotaste import sources

    for name, configs, revision in sources.DATASETS:
        for config in configs:
            load_dataset(name, config, revision=revision)
            print(f"cached {name} {config or ''} {revision or ''}", flush=True)


def procedural_families() -> dict:
    """Round 1's selection and blind2 families (family -> domain), unchanged."""
    data = yaml.safe_load(ROUND1_SUITES.read_text())
    domain = {f: "math" if v["category"] in MATH_CATEGORIES else "logic" for f, v in data["families"].items()}
    return {part: {f: domain[f] for f in data["suites"][part]} for part in ("selection", "blind2")}


def main() -> None:
    from evotaste import external, sources, tasks

    t0 = time.time()
    unit_domains = {s.unit: s.domain for s in sources.SOURCES.values() if s.role == "unseen"}
    units = external.draw_units(unit_domains)
    items, parts, reasons, _ = external.build(units, TOKENIZER)
    print(f"built {len(items)} candidates in {time.time() - t0:.0f} s", flush=True)
    alive = [k for k, r in enumerate(reasons) if r is None]
    gold = tasks.gold_reasons([tasks.make_task(items[k]) for k in alive])
    examples = collections.defaultdict(list)
    for k, why in zip(alive, gold):
        if why is not None:
            reasons[k] = "gold rejected"
            if parts[k] != external.VAULT and len(examples[items[k].source]) < 3:
                examples[items[k].source].append(f"{items[k].uid}: {why[:160]}")
    print(f"checked {len(alive)} references in {time.time() - t0:.0f} s", flush=True)
    for source, lines in examples.items():
        print(f"gold rejected in {source} (train/selection examples):", *lines, sep="\n  ")

    kept = collections.defaultdict(list)
    dropped = collections.defaultdict(collections.Counter)
    gold_failed = collections.defaultdict(list)
    for it, part, why in zip(items, parts, reasons):
        if why is None:
            kept[(it.source, part)].append(it.uid)
        else:
            dropped[it.source][f"{part}: {why}"] += 1
            if why == "gold rejected" and part != external.VAULT:
                gold_failed[it.source].append(it.id)
    part_table = {s: {p: {"items": len(kept[(s, p)]), "sha256": external.uid_hash(kept[(s, p)])}
                      for p in external.PARTS if kept[(s, p)]} for s in sources.SOURCES}
    suites = {p: [s for s in sources.SOURCES if kept[(s, p)]] for p in external.PARTS}
    if suites["train"] != list(sources.TRAINING_SOURCES):
        sys.exit(f"training sources without training items: {set(sources.TRAINING_SOURCES) - set(suites['train'])}")
    totals = {p: sum(len(kept[(s, p)]) for s in sources.SOURCES) for p in external.PARTS}
    header = ("# Generated by scripts/make_suites_r2.py; do not edit by hand. Single source of the Round 2 part\n"
              "# assignment (rules: evotaste/external.py). The vault (blind2) is listed by unit and count only; its\n"
              "# items are opened only by evaluate.py through the blind guard.\n")
    doc = {
        "generated": {"script": "scripts/make_suites_r2.py", "rules": {
            "split_seed": external.SPLIT_SEED_R2, "round1_split_seed": external.SPLIT_SEED,
            "sample_seed": sources.SAMPLE_SEED, "held_out_share": f"1/{external.HELD_OUT_SHARE} each",
            "near_jaccard": external.NEAR_JACCARD, "shingle_tokens": external.SHINGLE_TOKENS,
            "max_gold_chars": external.MAX_GOLD_CHARS, "max_prompt_tokens": external.MAX_PROMPT_TOKENS,
            "tokenizer": TOKENIZER}},
        "totals": totals,
        "units": {u: {"domain": unit_domains[u], "part": units[u]} for u in sorted(units)},
        "suites": suites,
        "procedural": procedural_families(),
        "parts": {s: v for s, v in part_table.items() if v},
        "dropped": {s: dict(sorted(c.items())) for s, c in dropped.items()},
        "gold_failed": {s: sorted(ids) for s, ids in gold_failed.items()},
    }
    OUT.write_text(header + yaml.safe_dump(doc, sort_keys=False, width=120))
    print(f"wrote {OUT}: {totals} in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--download", action="store_true", help="fill the dataset cache through the mirror and exit")
    args = ap.parse_args()
    download() if args.download else main()
